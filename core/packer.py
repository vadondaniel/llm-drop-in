from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import os
import re
import subprocess
import zipfile

PACKAGE_WORKTREE = "worktree"
PACKAGE_WORKTREE_IGNORED = "worktree-with-ignored"
PACKAGE_STAGED = "staged"
PACKAGE_HEAD = "head"


_WINDOWS_NO_CONSOLE = getattr(subprocess, "CREATE_NO_WINDOW", 0)


@dataclass(frozen=True)
class PackageResult:
    path: Path
    scope: str
    files: int
    size_bytes: int
    missing: tuple[str, ...] = ()


class PackageError(RuntimeError):
    """Raised when a project package cannot be created."""


def _git(root: Path, *args: str, input_bytes: bytes | None = None) -> bytes:
    try:
        completed = subprocess.run(
            ["git", "-C", str(root), *args],
            input=input_bytes,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
            creationflags=_WINDOWS_NO_CONSOLE,
        )
    except OSError as exc:
        raise PackageError(f"Could not start Git: {exc}") from exc
    if completed.returncode != 0:
        message = completed.stderr.decode("utf-8", errors="replace").strip()
        raise PackageError(message or f"Git failed: {' '.join(args)}")
    return completed.stdout


def _require_repo(root: Path) -> None:
    if not root.is_dir():
        raise PackageError(f"Project folder does not exist: {root}")
    try:
        value = _git(root, "rev-parse", "--is-inside-work-tree").decode(
            "ascii", errors="replace"
        ).strip()
    except PackageError as exc:
        raise PackageError(
            "The selected folder is not a Git working tree."
        ) from exc
    if value.lower() != "true":
        raise PackageError("The selected folder is not a Git working tree.")


def _decode_git_paths(data: bytes) -> list[str]:
    # Git's -z output is deliberately unquoted. Git path names are normally
    # UTF-8; surrogateescape preserves unusual byte sequences on disk.
    text = data.decode("utf-8", errors="surrogateescape")
    return [item for item in text.split("\0") if item]


def _worktree_files(
    root: Path, *, include_ignored: bool = False
) -> tuple[list[str], tuple[str, ...]]:
    tracked = _decode_git_paths(_git(root, "ls-files", "-z"))
    untracked = _decode_git_paths(
        _git(root, "ls-files", "-z", "--others", "--exclude-standard")
    )
    ignored = (
        _decode_git_paths(
            _git(
                root,
                "ls-files",
                "-z",
                "--others",
                "--ignored",
                "--exclude-standard",
            )
        )
        if include_ignored
        else []
    )

    seen: set[str] = set()
    relative: list[str] = []
    for name in [*tracked, *untracked, *ignored]:
        normalized = name.replace("\\", "/")
        if normalized in seen:
            continue
        seen.add(normalized)
        relative.append(normalized)

    included: list[tuple[str, Path]] = []
    missing: list[str] = []
    for name in relative:
        source = root / Path(*name.split("/"))
        if not source.is_file() or source.is_symlink():
            missing.append(name)
            continue
        included.append((name, source))

    included.sort(key=lambda pair: pair[0].casefold())
    missing.sort(key=str.casefold)
    return [name for name, _ in included], tuple(missing)


def _scope_name(scope: str) -> str:
    return {
        PACKAGE_WORKTREE: "",
        PACKAGE_WORKTREE_IGNORED: "-with-ignored",
        PACKAGE_STAGED: "-staged",
        PACKAGE_HEAD: "-head",
    }[scope]


def _output_path(root: Path, scope: str) -> Path:
    base = root.name or "project"
    return root.parent / f"{base}{_scope_name(scope)}.zip"


def _cleanup_obsolete_generated_packages(root: Path, scope: str, current: Path) -> None:
    """Remove archives generated by older versions of this app for this scope."""
    base = root.name or "project"
    scope_name = {
        PACKAGE_WORKTREE: "worktree",
        PACKAGE_WORKTREE_IGNORED: "worktree-with-ignored",
        PACKAGE_STAGED: "staged",
        PACKAGE_HEAD: "head",
    }[scope]
    patterns = (
        f"{base}-v*-{scope_name}.zip",
        f"{base}-{scope_name}-v*.zip",
        f"{base}-llm-{scope_name}-*.zip",
        f"{base}-llm-*.zip",
    )
    for pattern in patterns:
        for candidate in root.parent.glob(pattern):
            if candidate == current:
                continue
            # Only remove names that match the generated formats we have used.
            if not (
                (re.fullmatch(
                    rf"{re.escape(base)}-v\d+-{scope_name}\.zip", candidate.name, re.IGNORECASE))
                or (re.fullmatch(rf"{re.escape(base)}-{scope_name}-v\d+\.zip", candidate.name, re.IGNORECASE))
                or (re.fullmatch(rf"{re.escape(base)}-llm-{scope_name}-v\d+-\d{{8}}-\d{{6}}(?:-\d+)?\.zip", candidate.name, re.IGNORECASE))
                or (re.fullmatch(rf"{re.escape(base)}-llm-\d{{8}}-\d{{6}}(?:-\d+)?\.zip", candidate.name, re.IGNORECASE))
            ):
                continue
            try:
                candidate.unlink()
            except OSError:
                pass


def discover_latest_package(project_root: Path) -> PackageResult | None:
    """Find the newest generated package belonging to the selected project."""
    root = project_root.resolve()
    if not root.is_dir():
        return None

    candidates = []
    for scope in (
        PACKAGE_WORKTREE,
        PACKAGE_WORKTREE_IGNORED,
        PACKAGE_STAGED,
        PACKAGE_HEAD,
    ):
        path = _output_path(root, scope)
        if not path.is_file():
            continue
        try:
            stat = path.stat()
            with zipfile.ZipFile(path) as archive:
                files = sum(1 for item in archive.infolist()
                            if not item.is_dir())
        except (OSError, zipfile.BadZipFile):
            continue
        candidates.append((stat.st_mtime_ns, path, scope, files, stat.st_size))

    if not candidates:
        return None
    _, path, scope, files, size_bytes = max(
        candidates, key=lambda item: item[0])
    return PackageResult(
        path=path,
        scope=scope,
        files=files,
        size_bytes=size_bytes,
        missing=(),
    )


def _tree_entries(root: Path, treeish: str) -> list[tuple[str, str, str, str]]:
    """Return (mode, type, object_id, path) entries from a Git tree."""
    raw = _git(root, "ls-tree", "-r", "-z", "--full-tree", treeish)
    entries: list[tuple[str, str, str, str]] = []
    for record in raw.split(b"\0"):
        if not record:
            continue
        header, raw_path = record.split(b"\t", 1)
        mode, object_type, object_id = header.decode(
            "ascii"
        ).split(" ", 2)
        path = raw_path.decode("utf-8", errors="surrogateescape")
        entries.append((mode, object_type, object_id, path.replace("\\", "/")))
    return entries


def _archive_git_tree(root: Path, treeish: str, output: Path) -> int:
    """Write an exact tree snapshot without applying .gitattributes export-ignore."""
    entries = [
        entry for entry in _tree_entries(root, treeish)
        if entry[1] == "blob"
    ]

    process = subprocess.Popen(
        ["git", "-C", str(root), "cat-file", "--batch"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        creationflags=_WINDOWS_NO_CONSOLE,
    )
    assert process.stdin is not None
    assert process.stdout is not None

    try:
        with zipfile.ZipFile(
            output,
            mode="w",
            compression=zipfile.ZIP_DEFLATED,
            compresslevel=6,
        ) as archive:
            for mode, _object_type, object_id, path in entries:
                process.stdin.write((object_id + "\n").encode("ascii"))
                process.stdin.flush()

                header = process.stdout.readline()
                if not header:
                    raise PackageError(
                        "Git stopped while reading a tree snapshot.")
                parts = header.rstrip(b"\n").split(b" ", 2)
                if len(parts) != 3:
                    raise PackageError("Unexpected Git cat-file response.")
                _returned_id, returned_type, raw_size = parts
                if returned_type != b"blob":
                    raise PackageError(
                        f"Git returned {returned_type.decode('ascii', errors='replace')} "
                        f"for {path!r}."
                    )
                size = int(raw_size)
                info = zipfile.ZipInfo(path)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (int(mode, 8) & 0o777) << 16
                with archive.open(info, "w") as destination:
                    remaining = size
                    while remaining:
                        chunk = process.stdout.read(
                            min(1024 * 1024, remaining))
                        if not chunk:
                            raise PackageError(
                                f"Git ended the blob unexpectedly for {path!r}."
                            )
                        destination.write(chunk)
                        remaining -= len(chunk)
                if process.stdout.read(1) != b"\n":
                    raise PackageError(
                        "Git cat-file stream lost synchronization.")
    finally:
        try:
            process.stdin.close()
        except BrokenPipeError:
            pass
        stderr = process.stderr.read() if process.stderr is not None else b""
        return_code = process.wait()
        if process.stdout is not None:
            process.stdout.close()
        if process.stderr is not None:
            process.stderr.close()
        if return_code != 0:
            message = stderr.decode("utf-8", errors="replace").strip()
            raise PackageError(
                message or "Git could not read the tree snapshot.")

    return len(entries)


def _archive_worktree(
    root: Path, output: Path, *, include_ignored: bool = False
) -> tuple[int, tuple[str, ...]]:
    names, missing = _worktree_files(root, include_ignored=include_ignored)
    with zipfile.ZipFile(
        output,
        mode="w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=6,
    ) as archive:
        for name in names:
            source = root / Path(*name.split("/"))
            archive.write(source, arcname=name)
    return len(names), missing


def package_project(
    project_root: Path,
    *,
    scope: str = PACKAGE_WORKTREE,
    output_path: Path | None = None,
) -> PackageResult:
    root = project_root.resolve()
    if scope not in {
        PACKAGE_WORKTREE,
        PACKAGE_WORKTREE_IGNORED,
        PACKAGE_STAGED,
        PACKAGE_HEAD,
    }:
        raise ValueError(f"Unknown package scope: {scope}")

    _require_repo(root)
    output = output_path.resolve() if output_path is not None else _output_path(root, scope)
    output.parent.mkdir(parents=True, exist_ok=True)

    # Build completely in a temporary directory on the same filesystem, then
    # atomically replace the canonical package. The previous ZIP therefore
    # stays usable until the new archive has been created successfully.
    temp_dir = None
    temp_output = None
    try:
        import tempfile

        temp_dir = tempfile.TemporaryDirectory(
            dir=str(output.parent),
            prefix=f".{output.stem}-",
        )
        temp_output = Path(temp_dir.name) / output.name

        if scope == PACKAGE_WORKTREE:
            files, missing = _archive_worktree(root, temp_output)
        elif scope == PACKAGE_WORKTREE_IGNORED:
            files, missing = _archive_worktree(
                root, temp_output, include_ignored=True
            )
        elif scope == PACKAGE_HEAD:
            files = _archive_git_tree(root, "HEAD", temp_output)
            missing = ()
        else:
            # write-tree materializes the current index as a tree object. This
            # gives us the exact staged snapshot, including staged modifications
            # but excluding unstaged working-tree changes and untracked files.
            tree = _git(root, "write-tree").decode("ascii").strip()
            if not tree:
                raise PackageError("Git did not produce a staged tree.")
            files = _archive_git_tree(root, tree, temp_output)
            missing = ()

        size_bytes = temp_output.stat().st_size
        os.replace(temp_output, output)
    except Exception:
        raise
    finally:
        if temp_dir is not None:
            temp_dir.cleanup()

    _cleanup_obsolete_generated_packages(root, scope, output)

    return PackageResult(
        path=output,
        scope=scope,
        files=files,
        size_bytes=size_bytes,
        missing=missing,
    )
